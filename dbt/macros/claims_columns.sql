{#
  Shared typed projection for the two claim sources (bulk file + API increments) so
  both land in identical, explicitly typed, snake_case columns before the union.
#}
{% macro claims_columns(source_label) -%}
    cast(id as bigint)                                            as claim_id,
    '{{ source_label }}'                                          as record_source,
    cast(asOfDate as timestamp)                                   as source_as_of_ts,
    cast(dateOfLoss as date)                                      as date_of_loss,
    cast(yearOfLoss as integer)                                   as loss_year,
    cast(openDate as date)                                        as claim_open_date,
    cast(mostRecentPaymentDate as date)                           as most_recent_payment_date,
    upper(trim(state))                                            as state_abbr,
    nullif(trim(countyCode), '')                                  as county_fips,
    nullif(trim(censusGeoid), '')                                 as census_block_group_geoid,
    nullif(trim(reportedZipCode), '')                             as reported_zip,
    cast(latitude as double)                                      as latitude_approx,
    cast(longitude as double)                                     as longitude_approx,
    nullif(trim(nfipRatedCommunityNumber), '')                    as nfip_community_id,
    nullif(upper(trim(ratedFloodZone)), '')                       as rated_flood_zone,
    nullif(upper(trim(floodZoneCurrent)), '')                     as current_flood_zone,
    cast(occupancyType as integer)                                as occupancy_code,
    nullif(trim(causeOfDamage), '')                               as cause_code_raw,
    nullif(trim(floodEvent), '')                                  as flood_event_name,
    nullif(trim(eventDesignationNumber), '')                      as event_designation_number,
    cast(policyCount as integer)                                  as policy_count,
    cast(numberOfUnits as integer)                                as number_of_units,
    cast(primaryResidenceIndicator as boolean)                    as is_primary_residence,
    cast(elevatedBuildingIndicator as boolean)                    as is_elevated,
    cast(postFIRMConstructionIndicator as boolean)                as is_post_firm,
    cast(rentalPropertyIndicator as boolean)                      as is_rental,
    cast(numberOfFloorsInTheInsuredBuilding as integer)           as number_of_floors,
    cast(basementEnclosureCrawlspaceType as integer)              as basement_enclosure_type,
    cast(originalConstructionDate as date)                        as original_construction_date,
    cast(originalNBDate as date)                                  as original_new_business_date,
    nullif(trim(buildingDeductibleCode), '')                      as building_deductible_code,
    nullif(trim(contentsDeductibleCode), '')                      as contents_deductible_code,
    cast(totalBuildingInsuranceCoverage as double)                as building_coverage,
    cast(totalContentsInsuranceCoverage as double)                as contents_coverage,
    cast(iccCoverage as double)                                   as icc_coverage,
    cast(buildingDamageAmount as double)                          as building_damage,
    cast(contentsDamageAmount as double)                          as contents_damage,
    cast(buildingPropertyValue as double)                         as building_property_value,
    cast(buildingReplacementCost as double)                       as building_replacement_cost,
    cast(amountPaidOnBuildingClaim as double)                     as building_paid,
    cast(amountPaidOnContentsClaim as double)                     as contents_paid,
    cast(amountPaidOnIncreasedCostOfComplianceClaim as double)    as icc_paid,
    cast(netBuildingPaymentAmount as double)                      as building_paid_net,
    cast(netContentsPaymentAmount as double)                      as contents_paid_net,
    cast(netIccPaymentAmount as double)                           as icc_paid_net,
    cast(waterDepth as integer)                                   as water_depth_inches,
    cast(floodWaterDuration as integer)                           as flood_water_duration_hours,
    nullif(trim(nonPaymentReasonBuilding), '')                    as non_payment_reason_building
{%- endmacro %}
